// Generate TypeScript types from the exported JSON Schemas (FR-API-08, CLAUDE.md rule 5).
// The schemas in ../schemas are themselves generated from the Pydantic specs, so the
// backend, the LLM tool schemas and the frontend share one definition.
import { compile } from "json-schema-to-typescript";
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "..", "..", "schemas");
const outDir = join(here, "..", "src", "generated");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const banner = "/* GENERATED by scripts/gen-types.mjs from ../schemas - do not edit. */\n\n";
const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());
const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();
let index = banner;
for (const file of files) {
  const stem = file.replace(".schema.json", "");
  const name = pascal(stem);
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  delete schema.$id;
  schema.title = name;
  const ts = await compile(schema, name, {
    bannerComment: "",
    additionalProperties: false,
    unreachableDefinitions: false,
  });
  writeFileSync(join(outDir, `${stem}.ts`), banner + ts);
  index += `export type { ${name} } from "./${stem}";\n`;
}
writeFileSync(join(outDir, "index.ts"), index);
console.log(`generated ${files.length} spec type modules in src/generated`);
